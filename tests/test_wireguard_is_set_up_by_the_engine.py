def _inner(cmd: str) -> str:
    """the script a `pct exec N -- sh -c '<script>'` runs, unquoted the way the shell would"""
    return subprocess.run(["bash", "-c", "eval \"set -- ${0#*sh -c }\"; printf '%s' \"$1\"", cmd],
                          capture_output=True, text=True).stdout


def test_the_place_and_handshake_scripts_run(tmp_path):
    cmds, _, _ = wu.block(T7, REDRAFT)
    for c in cmds:
        assert subprocess.run(["bash", "-n", "-c", c], capture_output=True).returncode == 0, c
    hs = _inner(cmds[-1]).replace("seq 1 30", "seq 1 2").replace("sleep 1", "true")
    bin_ = tmp_path / "bin"; bin_.mkdir()
    (bin_ / "wg").write_text("#!/bin/sh\necho \"peerkey\t$HS\"\n"); (bin_ / "wg").chmod(0o755)
    (bin_ / "systemctl").write_text("#!/bin/sh\necho status\n"); (bin_ / "systemctl").chmod(0o755)
    env = {**os.environ, "PATH": f"{bin_}:{os.environ['PATH']}"}
    ok = subprocess.run(["sh", "-c", hs], capture_output=True, text=True, env={**env, "HS": "1792400000"})
    assert ok.returncode == 0 and "HANDSHAKE" in ok.stdout
    no = subprocess.run(["sh", "-c", hs], capture_output=True, text=True, env={**env, "HS": "0"})
    assert no.returncode == 1 and "never completed a handshake" in no.stdout


def _bin(tmp_path, **tools):
    b = tmp_path / "bin"; b.mkdir(exist_ok=True)
    for name, body in tools.items():
        (b / name).write_text("#!/bin/bash\n" + body); (b / name).chmod(0o755)
    return {**os.environ, "PATH": f"{b}:{os.environ['PATH']}"}


def test_the_resolv_conf_resolvconf_emptied_is_written_back(tmp_path):
    """live, CT 109: resolvconf left /etc/resolv.conf a symlink to an empty file; the container's own nameservers return"""
    g = tmp_path / "guest"; g.mkdir()
    (g / "run.conf").write_text("# generated by resolvconf\n")
    (g / "resolv.conf").symlink_to(g / "run.conf")
    env = _bin(tmp_path, pct=(
        'case "$1" in\n'
        '  config) printf "hostname: bitmagnet\\nnameserver: 192.168.1.1 1.1.1.1\\nunprivileged: 1\\n";;\n'
        f'  exec) shift 3; case "$1" in test) [ -L {g}/resolv.conf ];; rm) rm -f {g}/resolv.conf;; esac;;\n'
        f'  push) cp "$3" {g}/resolv.conf;;\n'
        'esac\n'))
    restore = next(c for c in wu.block(T7, REDRAFT)[0] if "test -L /etc/resolv.conf" in c)
    r = subprocess.run(["bash", "-c", restore], capture_output=True, text=True, env=env)
    assert r.returncode == 0 and "RESTORED" in r.stdout, r
    assert not (g / "resolv.conf").is_symlink()
    assert (g / "resolv.conf").read_text() == ("# --- BEGIN PVE ---\nnameserver 192.168.1.1\nnameserver 1.1.1.1\n"
                                               "# --- END PVE ---\n")
    again = subprocess.run(["bash", "-c", restore], capture_output=True, text=True, env=env)
    assert "is a plain file" in again.stdout                                   # a second run changes nothing


def test_an_endpoint_that_does_not_resolve_stops_the_step_before_the_start(tmp_path):
    conf = tmp_path / "wg.conf"
    conf.write_text("[Interface]\nAddress = 10.0.0.2/32\n\n[Peer]\nEndpoint = ch3.vpn.airdns.org:1637\n")
    node = {**T7, "prompt_template": f"set up wg0 from {conf} in CT 109."}
    resolve = _inner(next(c for c in wu.block(node, REDRAFT)[0] if "getent hosts" in c))
    ok = subprocess.run(["sh", "-c", resolve], capture_output=True, text=True,
                        env=_bin(tmp_path, getent='echo "1.2.3.4 $2"'))
    assert ok.returncode == 0 and "ENDPOINT RESOLVES: ch3.vpn.airdns.org" in ok.stdout, ok
    no = subprocess.run(["sh", "-c", resolve], capture_output=True, text=True, env=_bin(tmp_path, getent="exit 2"))
    assert no.returncode == 1 and "cannot resolve ch3.vpn.airdns.org" in no.stdout
    conf.write_text("[Peer]\nEndpoint = 185.1.2.3:1637\n")                    # an address needs no lookup
    lit = subprocess.run(["sh", "-c", resolve], capture_output=True, text=True, env=_bin(tmp_path, getent="exit 2"))
    assert lit.returncode == 0 and "185.1.2.3" in lit.stdout


